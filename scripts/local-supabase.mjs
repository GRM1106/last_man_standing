import { spawnSync, spawn } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, chmodSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import { LOCAL_PROJECT_ID, LOCAL_SUPABASE_URL, assertLocalKey } from '../server/environment.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const cli = fileURLToPath(new URL('../node_modules/.bin/supabase', import.meta.url));
const action = process.argv[2];
const marker = '# Generated by LMS local:setup; local credentials only.\n';
// Do not inherit hosted service credentials, CLI project overrides or cloud credentials.
const env = Object.fromEntries(['PATH', 'HOME', 'USER', 'LOGNAME', 'TMPDIR', 'DOCKER_HOST', 'DOCKER_CONTEXT', 'DOCKER_CONFIG', 'TERM']
  .filter(key => process.env[key]).map(key => [key, process.env[key]]));
function run(args) {
  const result = spawnSync(cli, args, { cwd: root, env, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  if (result.error || result.status !== 0) throw new Error(`Local Supabase ${args[0]} failed. Check Docker and the local CLI installation; no hosted fallback is permitted.`);
  return result.stdout;
}
function generatedFile(path, contents) {
  if (existsSync(path) && !readFileSync(path, 'utf8').startsWith(marker)) {
    throw new Error(`Refusing to overwrite existing private configuration: ${path.slice(root.length)}. Review it and move it aside before local:setup.`);
  }
  writeFileSync(path, marker + contents, { mode: 0o600 });
  chmodSync(path, 0o600);
}
try {
  if (!['start', 'setup', 'functions', 'migrate'].includes(action) || process.argv.length !== 3) throw new Error('Use local:start, local:setup, local:functions or local:migrate without extra arguments.');
  const config = readFileSync(root + 'supabase/config.toml', 'utf8');
  if (!config.includes(`project_id = "${LOCAL_PROJECT_ID}"`) || !config.includes('port = 55321') || !config.includes('port = 55322')) throw new Error('Local project identity/ports do not match the isolated LMS configuration.');
  for (const path of ['supabase/functions/.env', 'supabase/functions/lms-scheduler/.env']) {
    if (existsSync(root + path)) throw new Error(`Review and move aside ${path} before starting local functions; ambient function secrets are not accepted.`);
  }
  if (action === 'start') {
    console.log('Starting the isolated last_man_standing_local stack and repository migrations…');
    run(['start']);
    console.log('Local Supabase started. Run npm run local:setup next.');
  } else if (action === 'migrate') {
    run(['migration', 'up', '--local']);
    console.log('Pending repository migrations applied to the local database only.');
  } else if (action === 'setup') {
    const status = JSON.parse(run(['status', '-o', 'json']));
    if (status.API_URL !== LOCAL_SUPABASE_URL) throw new Error('CLI status did not identify the expected local API; refusing to generate configuration.');
    const anon = assertLocalKey(status.ANON_KEY, 'anon');
    assertLocalKey(status.SERVICE_ROLE_KEY, 'service_role');
    generatedFile(root + '.env.development.local', `LMS_LOCAL_SUPABASE_URL=${LOCAL_SUPABASE_URL}\nLMS_LOCAL_SUPABASE_ANON_KEY=${anon}\n`);
    const functionFile = root + 'supabase/.env.local';
    if (!existsSync(functionFile)) generatedFile(functionFile, `LMS_SEASON=2026/27\nLMS_SCHEDULER_SECRET=${randomBytes(32).toString('hex')}\n`);
    else if (!readFileSync(functionFile, 'utf8').startsWith(marker)) throw new Error('Review existing supabase/.env.local before local:setup.');
    console.log('Generated ignored local browser/function configuration. No service credential was copied into browser configuration.');
  } else {
    if (!existsSync(root + 'supabase/.env.local')) throw new Error('Run npm run local:setup before local:functions.');
    const contents = readFileSync(root + 'supabase/.env.local', 'utf8');
    if (!contents.startsWith(marker) || contents.split('\n').some(line => line.trim() && !line.startsWith('#') && !/^(LMS_SEASON|LMS_SCHEDULER_SECRET)=/.test(line))) {
      throw new Error('Local function configuration contains unsupported overrides; only local season and scheduler secret are permitted.');
    }
    console.log('Serving local Edge Functions; no scheduled polling is started.');
    const child = spawn(cli, ['functions', 'serve', '--env-file', 'supabase/.env.local'], { cwd: root, env, stdio: 'inherit' });
    for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
    child.on('exit', code => { process.exitCode = code ?? 1; });
  }
} catch (error) { console.error(error.message); process.exitCode = 1; }
